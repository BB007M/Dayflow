// Generate recent 14 days of realistic attendance for our employees
export const generateInitialAttendance = (): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const today = new Date();
  
  // Last 14 days
  for (let i = 13; i >= 0; i--) {
    const d = new Date();
    d.setDate(today.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    const dayOfWeek = d.getDay(); // 0 = Sunday, 6 = Saturday

    INITIAL_EMPLOYEES.forEach((emp) => {
      let status: AttendanceRecord['status'] = 'present';
      let checkIn: string | null = '08:58 AM';
      let checkOut: string | null = '05:30 PM';
      let totalHours = 8.5;
      let breakMinutes = 45;

      if (dayOfWeek === 0 || dayOfWeek === 6) {
        status = 'weekend';
        checkIn = null;
        checkOut = null;
        totalHours = 0;
        breakMinutes = 0;
      } else {
        // Deterministic simulation
        if (emp.employeeId === 'EMP-1042' && i === 3) {
          status = 'leave';
          checkIn = null;
          checkOut = null;
          totalHours = 0;
        } else if (emp.employeeId === 'EMP-1089' && i === 5) {
          status = 'half-day';
          checkIn = '09:00 AM';
          checkOut = '01:15 PM';
          totalHours = 4.25;
        } else if (emp.employeeId === 'EMP-1120' && i === 8) {
          status = 'absent';
          checkIn = null;
          checkOut = null;
          totalHours = 0;
        } else if (i === 0) {
          // Today's attendance
          if (emp.employeeId === 'EMP-1001') {
            status = 'present';
            checkIn = '08:45 AM';
            checkOut = null; // currently in office
            totalHours = 5.6;
          } else if (emp.employeeId === 'EMP-1042') {
            status = 'present';
            checkIn = '09:12 AM';
            checkOut = null;
            totalHours = 5.2;
          } else if (emp.employeeId === 'EMP-1089') {
            status = 'leave';
            checkIn = null;
            checkOut = null;
            totalHours = 0;
          } else {
            status = 'present';
            checkIn = '09:00 AM';
            checkOut = null;
            totalHours = 5.4;
          }
        }
      }

      records.push({
        id: `att-${emp.employeeId}-${dateStr}`,
        employeeId: emp.employeeId,
        date: dateStr,
        checkInTime: checkIn,
        checkOutTime: checkOut,
        totalHoursWorked: totalHours,
        breakMinutes: breakMinutes,
        status: status,
      });
    });
  }

  return records;
};

